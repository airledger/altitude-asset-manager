-- Equipment and parts catalogue (part 2). Adding a unit, the engineer picks the manufacturer, then the range
-- and size, and the form fills in the rest; or they type it in, as before. Air Ledger's own list is shared by
-- every business (org_id null) and is a starting point: no complete public list of every model exists. Every
-- model a business types in is kept in its own catalogue (org_id set), with the refrigerant and factory charge
-- of its install once known, so the next one is a pick. The same goes for parts: a shared list of common AC
-- parts to pick from when adding to the materials list, and "install" kit that only goes on install jobs.
--
-- Factory charges are not pre-loaded in the shared list on purpose: the charge sets the F-gas leak-check
-- interval, so it comes from the unit's rating plate the first time and is remembered after that.

create table public.equipment_models (
  id uuid primary key default gen_random_uuid(),
  org_id uuid references public.orgs on delete cascade,
  manufacturer text not null check (btrim(manufacturer) <> ''),
  range text not null default '',
  model text not null default '',
  role text not null check (role in ('indoor', 'outdoor')),
  indoor_type text check (indoor_type in ('Wall mounted', 'Cassette', 'Ducted', 'Floor console', 'Ceiling suspended', 'Other')),
  capacity_kw numeric check (capacity_kw >= 0),
  refrigerant text not null default '',
  charge_kg numeric check (charge_kg >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid default auth.uid() references auth.users on delete set null,
  check (role = 'indoor' or indoor_type is null)
);
-- One entry per model in each catalogue (Air Ledger's, or a business's own).
create unique index equipment_models_one_per_model on public.equipment_models
  (coalesce(org_id, '00000000-0000-0000-0000-000000000000'::uuid), lower(manufacturer), lower(model))
  where model <> '';
create index on public.equipment_models (org_id, lower(manufacturer));
alter table public.equipment_models enable row level security;
revoke all on public.equipment_models from anon;
create policy "read" on public.equipment_models for select to authenticated
  using (org_id is null or public.is_member(org_id));
create policy "add" on public.equipment_models for insert to authenticated
  with check (org_id is not null and public.is_member(org_id));
create policy "edit" on public.equipment_models for update to authenticated
  using (org_id is not null and public.is_member(org_id)) with check (org_id is not null and public.is_member(org_id));
create policy "delete" on public.equipment_models for delete to authenticated
  using (org_id is not null and public.is_owner(org_id));
create trigger touch before update on public.equipment_models for each row execute function public.touch_updated_at();

-- ---------- learning from what's typed ----------
-- A unit saved with a model that isn't in Air Ledger's list goes in the business's own catalogue. An outdoor
-- unit takes its install's refrigerant and factory charge with it, when they're set.
create or replace function public.learn_equipment(p_org uuid, p_manufacturer text, p_model text, p_role text,
  p_indoor_type text, p_capacity numeric, p_refrigerant text, p_charge numeric) returns void
language plpgsql security definer set search_path = public as $$
begin
  if btrim(coalesce(p_manufacturer, '')) = '' or btrim(coalesce(p_model, '')) = '' then return; end if;
  if exists (select 1 from public.equipment_models where org_id is null
             and lower(manufacturer) = lower(btrim(p_manufacturer)) and lower(model) = lower(btrim(p_model))
             and charge_kg is not null) then
    return;
  end if;
  insert into public.equipment_models as e (org_id, manufacturer, model, role, indoor_type, capacity_kw, refrigerant, charge_kg)
    values (p_org, btrim(p_manufacturer), btrim(p_model), p_role,
            case when p_role = 'indoor' then p_indoor_type end, p_capacity, coalesce(p_refrigerant, ''),
            case when p_role = 'outdoor' then p_charge end)
    on conflict (coalesce(org_id, '00000000-0000-0000-0000-000000000000'::uuid), lower(manufacturer), lower(model))
      where model <> ''
    do update set
      role = excluded.role,
      indoor_type = excluded.indoor_type,
      capacity_kw = coalesce(excluded.capacity_kw, e.capacity_kw),
      refrigerant = coalesce(nullif(excluded.refrigerant, ''), e.refrigerant),
      charge_kg = coalesce(excluded.charge_kg, e.charge_kg);
end $$;
revoke all on function public.learn_equipment(uuid, text, text, text, text, numeric, text, numeric) from public, anon, authenticated;

create or replace function public.learn_from_unit() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  s public.systems;
begin
  select * into s from public.systems where id = new.system_id;
  perform public.learn_equipment(new.org_id, new.manufacturer, new.model, new.role, new.indoor_type,
    new.capacity_kw, s.refrigerant, s.factory_charge_kg);
  return null;
end $$;
revoke all on function public.learn_from_unit() from public, anon, authenticated;
create trigger learn_equipment after insert or update of manufacturer, model, capacity_kw, role, indoor_type
  on public.units for each row execute function public.learn_from_unit();

-- The install's refrigerant or factory charge set later: remember it against its outdoor units' models.
create or replace function public.learn_from_system() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  u record;
begin
  for u in select * from public.units where system_id = new.id and role = 'outdoor' loop
    perform public.learn_equipment(u.org_id, u.manufacturer, u.model, u.role, u.indoor_type, u.capacity_kw,
      new.refrigerant, new.factory_charge_kg);
  end loop;
  return null;
end $$;
revoke all on function public.learn_from_system() from public, anon, authenticated;
create trigger learn_equipment after update of refrigerant, factory_charge_kg on public.systems
  for each row when (new.refrigerant is distinct from old.refrigerant
                     or new.factory_charge_kg is distinct from old.factory_charge_kg)
  execute function public.learn_from_system();

